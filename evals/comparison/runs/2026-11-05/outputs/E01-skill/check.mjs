import assert from 'node:assert/strict';
import { ImpactPresentation, simulate } from './impact.mjs';
const msg = (id, revision, state, round = 'round-1', x = revision) => ({ id, revision, state, round, point: { x, y: 0 } });
for (const initial of ['pending', 'confirmed']) {
  const p = new ImpactPresentation();
  p.receive(msg('a', 1, initial));
  p.finish('a');
  p.finish('a');
  const bursts = p.bursts;
  assert.equal(p.receive(msg('a', 2, 'confirmed')), true);
  assert.equal(p.active.has('a'), false, `${initial}: finished effect resurrected`);
  assert.equal(p.bursts, bursts, `${initial}: late burst`);
  assert.equal(p.events.get('a').revision, 2);
  assert.equal(p.receive(msg('a', 1, initial)), false);
  assert.equal(p.receive(msg('a', 2, 'confirmed')), false);
  assert.equal(p.receive(msg('a', 3, 'pending')), false);
  p.receive(msg('a', 3, 'rejected'));
  p.receive(msg('a', 4, 'confirmed'));
  assert.equal(p.active.has('a'), false);
  assert.equal(p.bursts, bursts);
  p.receive(msg('b', 1, 'confirmed'));
  assert.equal(p.active.get('b').kind, 'impact');
  assert.equal(p.bursts, bursts + 1);
  p.nextRound('round-2');
  assert.equal(p.events.size, 0);
  assert.equal(p.active.size, 0);
  assert.equal(p.receive(msg('a', 5, 'confirmed')), false);
  p.receive(msg('a', 1, 'confirmed', 'round-2'));
  assert.equal(p.active.has('a'), true);
  assert.equal(p.bursts, bursts + 2);
  p.dispose();
  assert.equal(p.events.size, 0);
  assert.equal(p.active.size, 0);
  assert.equal(p.receive(msg('c', 1, 'confirmed', 'round-2')), false);
  assert.throws(() => p.nextRound('round-3'), /disposed owner/);
}
const p = new ImpactPresentation();
p.receive(msg('a', 1, 'pending'));
assert.equal(p.active.get('a').kind, 'preview');
assert.equal(p.bursts, 0);
p.receive(msg('a', 3, 'pending'));
assert.equal(p.active.get('a').point.x, 3);
assert.equal(p.receive(msg('a', 2, 'confirmed')), false);
p.receive(msg('a', 4, 'confirmed'));
assert.equal(p.active.get('a').kind, 'impact');
assert.equal(p.bursts, 1);
p.receive(msg('a', 5, 'confirmed'));
assert.equal(p.active.get('a').point.x, 5);
assert.equal(p.bursts, 1);
p.receive(msg('a', 6, 'rejected'));
assert.equal(p.active.has('a'), false);
p.receive(msg('a', 7, 'confirmed'));
assert.equal(p.active.has('a'), true);
assert.equal(p.bursts, 1);
p.finish('unseen');
p.receive(msg('unseen', 1, 'confirmed'));
assert.equal(p.active.has('unseen'), false);
assert.equal(p.bursts, 1);
assert.throws(() => p.receive(msg('invalid', 0, 'confirmed')), TypeError);
assert.throws(() => p.receive(msg('invalid', 1, 'unknown')), TypeError);
const q = new ImpactPresentation();
assert.deepEqual(simulate(e => q.receive(e)), simulate());
assert.equal(q.bursts, 1);
console.log('PASS: finish lifecycle, revisions, corrections, round/disposal, validation, simulation equivalence');
