import assert from 'node:assert/strict';
import { ImpactPresentation, simulate } from './impact.mjs';
const msg = (id, revision, state = 'confirmed', round = 'round-1', x = revision) => ({ id, revision, state, round, point: { x, y: 0 } });
const p = new ImpactPresentation();
assert.equal(p.receive(msg('a', 1)), true);
p.finish('a');
assert.equal(p.receive(msg('a', 2)), true);
assert.equal(p.active.has('a'), false, 'finished confirmed effect must not return');
assert.equal(p.bursts, 1);
assert.equal(p.receive(msg('a', 2)), false);
assert.equal(p.receive(msg('a', 1)), false);
assert.equal(p.receive(msg('a', 3, 'pending')), false);
assert.equal(p.events.get('a').revision, 2);
p.receive(msg('b', 1, 'pending'));
assert.equal(p.active.get('b').kind, 'preview');
p.finish('b');
p.finish('b');
assert.equal(p.receive(msg('b', 2)), true);
assert.equal(p.active.has('b'), false, 'finished preview must not return on confirmation');
assert.equal(p.bursts, 1, 'finished preview must not emit success burst');
assert.equal(p.events.get('b').confirmedBefore, true);
p.receive(msg('b', 3, 'rejected'));
p.receive(msg('b', 4));
assert.equal(p.active.has('b'), false);
assert.equal(p.bursts, 1);
p.finish('not-yet-seen');
p.receive(msg('not-yet-seen', 1));
assert.equal(p.active.has('not-yet-seen'), false);
assert.equal(p.bursts, 1);
p.receive(msg('c', 1, 'pending'));
p.receive(msg('c', 3, 'pending', 'round-1', 30));
assert.deepEqual(p.active.get('c'), { kind: 'preview', point: { x: 30, y: 0 } });
assert.equal(p.receive(msg('c', 2)), false);
p.receive(msg('c', 4));
assert.equal(p.active.get('c').kind, 'impact');
assert.equal(p.bursts, 2);
p.receive(msg('c', 5, 'confirmed', 'round-1', 50));
assert.equal(p.active.get('c').point.x, 50);
assert.equal(p.bursts, 2);
p.receive(msg('c', 6, 'rejected'));
assert.equal(p.active.has('c'), false);
assert.equal(p.receive(msg('c', 7, 'pending')), false);
p.receive(msg('c', 8));
assert.equal(p.active.has('c'), true, 'rejection alone retains existing behavior');
assert.equal(p.bursts, 2);
assert.throws(() => p.receive(msg('bad', 0)), TypeError);
assert.throws(() => p.receive(msg('bad', 1, 'unknown')), TypeError);
assert.equal(p.receive(msg('foreign', 1, 'confirmed', 'old-round')), false);
p.nextRound('round-2');
assert.equal(p.events.size, 0);
assert.equal(p.active.size, 0);
assert.equal(p.receive(msg('a', 1)), false);
p.receive(msg('a', 1, 'confirmed', 'round-2'));
assert.equal(p.active.has('a'), true);
assert.equal(p.bursts, 3);
p.finish('a');
p.dispose();
assert.equal(p.events.size, 0);
assert.equal(p.active.size, 0);
assert.equal(p.receive(msg('a', 2, 'confirmed', 'round-2')), false);
assert.throws(() => p.nextRound('round-3'), /disposed owner/);
assert.deepEqual(simulate(e => new ImpactPresentation().receive(e)), simulate());
console.log('All impact lifecycle checks passed.');
